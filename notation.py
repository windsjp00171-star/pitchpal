SP = 10                      # 線距（SVG 單位）
SCALE = SP * 4 / 1000        # 字型單位 -> SVG 單位（1 em = 4 個線距）
STEP = SP / 2                # 半個線距 = 一個音階級進

# 調號中各升降記號的位置：距離最上線的級進數（高音譜表）
_SHARP_STEPS = (0, 3, -1, 2, 5, 1, 4)    # F C G D A E B
_FLAT_STEPS = (4, 1, 5, 2, 6, 3, 7)      # B E A D G C F


def signature(root: int, mode: str) -> tuple[str, int]:
    """回傳 ("sharp" | "flat" | "", 數量)。以五度圈位置推算。"""
    major_root = root if mode == "大調" else (root + 3) % 12
    fifths = (major_root * 7) % 12
    if fifths == 0:
        return "", 0
    return ("sharp", fifths) if fifths <= 6 else ("flat", 12 - fifths)


def staff_svg(root: int, mode: str, color: str) -> str:
    kind, n = signature(root, mode)
    width = 56 + max(n, 1) * 13 + 10
    lines = "".join(
        f'<line x1="0" y1="{i * SP}" x2="{width}" y2="{i * SP}" stroke="#16130f" stroke-width="1.6"/>' for i in range(5)
    )
    clef = (f'<path d="{GLYPHS["gclef"]}" transform="translate(4 {3 * SP}) scale({SCALE} {-SCALE})" fill="#16130f"/>')
    marks = ""
    steps = _SHARP_STEPS if kind == "sharp" else _FLAT_STEPS
    for k in range(n):
        x = 52 + k * 13
        y = steps[k] * STEP
        marks += (f'<path d="{GLYPHS[kind]}" transform="translate({x} {y}) scale({SCALE} {-SCALE})" fill="{color}"/>')
    label = "沒有升降記號" if n == 0 else (f"{n} 個升記號" if kind == "sharp" else f"{n} 個降記號")
    return (f'<svg class="pp-staff-svg" viewBox="-2 -26 {width + 4} 92" style="width:{(width + 4) * 1.7:.0f}px" role="img" aria-label="調號：{label}">'
            f'{lines}{clef}{marks}</svg>')
